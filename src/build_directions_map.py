import pandas as pd
from pathlib import Path

UNIQUE_PATH = Path("data/processed/unique_disciplines.csv")
OUTPUT_PATH = Path("data/processed/discipline_directions.csv")

COL_DISC = "DisciplineName"


def detect_direction(name: str) -> str:
    """
    Простейшая эвристика по ключевым словам.
    Если что-то классифицируется странно — потом поправим руками
    в discipline_directions.csv.
    """
    n = name.lower()

    # --- IT / программирование ---
    if any(x in n for x in [
        "программир", "алгоритм", "структуры данных",
        "web", "веб", "интерфейс", "интернет-приложений",
        "базы данных", "база данных",
        "информационн", "it ", " it-", " it ",
        "компьютерн", "операционн", "сетев", "компьютерные сети",
        "программное обеспечение", "software"
    ]):
        # отдельно Data / AI
        if any(x in n for x in [
            "анализ данных", "data", "машинное обучение",
            "искусственный интеллект", "интеллектуальн", "data mining"
        ]):
            return "Data / AI"
        return "IT / Программирование"

    # --- Data / AI (если не поймали выше) ---
    if any(x in n for x in [
        "анализ данных", "машинное обучение", "искусственный интеллект",
        "интеллектуальные системы", "интеллектуальный анализ",
        "data mining", "big data"
    ]):
        return "Data / AI"

    # --- Электроника и телеком ---
    if any(x in n for x in [
        "электро", "радио", "телекоммуникац", "антенно",
        "микроконтроллер", "микропроцессор", "наносенсор",
        "радиотехническ", "сети связи", "цепи и сигналы",
        "цифровые устройства", "электропривод", "электроэнергет",
        "электрические машины", "электроснабжение", "электрические станции",
        "электротехника"
    ]):
        return "Электроника и телеком"

    # --- Машиностроение ---
    if any(x in n for x in [
        "машиностро", "станки", "детали машин", "технология производства машин",
        "технологические процессы машиностроительного", "конструкционные материалы",
        "термообработка", "резания", "свароч", "оснастк", "станков с числовым программным управлением"
    ]):
        return "Машиностроение"

    # --- Транспорт ---
    if any(x in n for x in [
        "транспортн", "вагон", "автомоб", "двигател", "дорожного движения",
        "железнодорож", "эксплуатация транспортной техники", "транспортной техники",
        "подвижной состав"
    ]):
        return "Транспорт"

    # --- Строительство / Архитектура ---
    if any(x in n for x in [
        "архитектур", "зданий", "сооружений", "строительн",
        "геодез", "геотехник", "железобетон", "конструкци",
        "строительная механика", "строительное черчение", "bim"
    ]):
        return "Строительство / Архитектура"

    # --- Измерения / метрология / качество ---
    if any(x in n for x in [
        "метролог", "измерен", "испытан", "контроль качества",
        "сертификац", "аккредитац", "квалиметр", "стандартизац",
        "поверка", "статистические методы управления качеством"
    ]):
        return "Измерения / Метрология / Качество"

    # --- Дизайн / искусство ---
    if any(x in n for x in [
        "дизайн", "график", "иллюстрац", "живопись", "рисунок",
        "шрифт", "книга", "цветовед", "стили и направления в изобразительном искусстве",
        "архитектурного дизайна", "графического дизайна"
    ]):
        return "Дизайн / Искусство"

    # --- Математика / физика ---
    if any(x in n for x in [
        "математ", "математика", "дифференциальные уравнения",
        "вычислительная математика", "физика", "теоретическая механика",
        "сопротивление материалов", "моделирован", "вероятност", "статистик"
    ]):
        return "Математика / Физика"

    # --- Экономика / менеджмент / логистика ---
    if any(x in n for x in [
        "экономик", "предпринимательств", "логистик",
        "менеджмент", "управленческие решения", "управление качеством",
        "управление проектами", "управление it", "экономические информационные системы"
    ]):
        return "Экономика / Менеджмент"

    # --- Гуманитарные науки ---
    if any(x in n for x in [
        "история", "философ", "культуролог", "социолог", "политолог",
        "этика", "риторика", "критическое и креативное мышление",
        "этика в цифровом мире"
    ]):
        return "Гуманитарные науки"

    # --- Языки ---
    if any(x in n for x in [
        "язык", "английский", "казахский", "русский", "иностранный",
        "профессиональный английский"
    ]):
        return "Языки"

    # --- Софт-скиллы / общие компетенции ---
    if any(x in n for x in [
        "служение обществу",
        "основы эконом",  # уже в экономике, но на всякий
        "основы права", "правового регулирования",
        "лидерство", "управление инновациями",
        "культура и этика академического письма",
        "основы академического письма",
        "технологии формирования профессионального имиджа"
    ]):
        return "Софт-скиллы / Общие компетенции"

    # --- Физкультура ---
    if "физическая культура" in n:
        return "Физкультура"

    # Фоллбэк
    return "Другое"


def main():
    df = pd.read_csv(UNIQUE_PATH)
    df.columns = df.columns.str.strip()

    if COL_DISC not in df.columns:
        raise ValueError(f"Колонка {COL_DISC} не найдена в {UNIQUE_PATH}")

    df["Direction"] = df[COL_DISC].astype(str).apply(detect_direction)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_PATH, index=False)

    print(f"Unique disciplines: {len(df)}")
    print(f"Saved with directions to: {OUTPUT_PATH}")
    print(df.head(20))


if __name__ == "__main__":
    main()
